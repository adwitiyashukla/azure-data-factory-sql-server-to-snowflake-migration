CREATE OR REPLACE PROCEDURE CORE.MERGE_FROM_STG(TABLE_NAME VARCHAR, KEY_COLUMN VARCHAR)
RETURNS NUMBER
LANGUAGE SQL
AS
$$
DECLARE
    col_list VARCHAR;
    set_list VARCHAR;
    val_list VARCHAR;
    stmt VARCHAR;
    inserted NUMBER;
    updated NUMBER;
BEGIN
    SELECT LISTAGG(COLUMN_NAME, ', ') WITHIN GROUP (ORDER BY ORDINAL_POSITION),
           LISTAGG('t.' || COLUMN_NAME || ' = s.' || COLUMN_NAME, ', ') WITHIN GROUP (ORDER BY ORDINAL_POSITION),
           LISTAGG('s.' || COLUMN_NAME, ', ') WITHIN GROUP (ORDER BY ORDINAL_POSITION)
      INTO :col_list, :set_list, :val_list
      FROM ADFMIG.INFORMATION_SCHEMA.COLUMNS
     WHERE TABLE_SCHEMA = 'STG'
       AND TABLE_NAME = :TABLE_NAME;

    stmt := 'MERGE INTO CORE.' || TABLE_NAME || ' t USING (SELECT * FROM STG.' || TABLE_NAME ||
            ' QUALIFY ROW_NUMBER() OVER (PARTITION BY ' || KEY_COLUMN || ' ORDER BY UPDATED_AT DESC) = 1) s' ||
            ' ON t.' || KEY_COLUMN || ' = s.' || KEY_COLUMN ||
            ' WHEN MATCHED THEN UPDATE SET ' || set_list ||
            ' WHEN NOT MATCHED THEN INSERT (' || col_list || ') VALUES (' || val_list || ')';
    EXECUTE IMMEDIATE :stmt;

    SELECT "number of rows inserted", "number of rows updated"
      INTO :inserted, :updated
      FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()));

    INSERT INTO CORE.LOAD_LOG (TABLE_NAME, ROWS_INSERTED, ROWS_UPDATED)
    VALUES (:TABLE_NAME, :inserted, :updated);

    RETURN inserted + updated;
END;
$$;
